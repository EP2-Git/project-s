import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, readdir, realpath, rm, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageNames = ['contracts', 'application'];
const outputParts = ['supabase', 'functions', '_shared', '.generated'];
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');

const exists = async (path) => {
  try { return await lstat(path); } catch (error) {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  }
};

const assertInside = (root, path) => {
  const child = relative(root, path);
  assert.ok(child !== '' && child !== '..' && !child.startsWith(`..${sep}`)
    && !isAbsolute(child), 'Generated path must stay inside the repository');
  assert.equal(resolve(root, child), path, 'Unexpected generated path');
};

const inspectPath = async (root, parts) => {
  let current = root;
  for (const part of parts) {
    current = join(current, part);
    const stat = await exists(current);
    if (stat === undefined) return undefined;
    assert.ok(!stat.isSymbolicLink(), `Refusing linked package path: ${current}`);
    assert.equal(await realpath(current), current, `Refusing redirected package path: ${current}`);
  }
  return current;
};

const collectFiles = async (directory, prefix = '') => {
  const files = [];
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name);
    const stat = await lstat(path);
    assert.ok(!stat.isSymbolicLink(), `Refusing linked package entry: ${path}`);
    assert.equal(await realpath(path), path, `Refusing redirected package entry: ${path}`);
    const name = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (stat.isDirectory()) files.push(...await collectFiles(path, name));
    else {
      assert.ok(stat.isFile(), `Refusing non-file package entry: ${path}`);
      files.push({ path: name, content: await readFile(path) });
    }
  }
  return files;
};

/** Mirror only built shared packages into the existing functions bind mount. */
export const prepareEdgePackages = async ({ root = repositoryRoot } = {}) => {
  const canonicalRoot = await realpath(resolve(root));
  const directory = join(canonicalRoot, ...outputParts);
  assertInside(canonicalRoot, directory);
  assert.equal(relative(canonicalRoot, directory), outputParts.join(sep));

  // Validate and snapshot every source before changing any previous output.
  const files = [];
  for (const packageName of packageNames) {
    for (const tree of ['dist', 'src']) {
      const parts = ['packages', packageName, tree];
      const source = await inspectPath(canonicalRoot, parts);
      assert.ok(source, `Missing built package tree: ${parts.join('/')}`);
      assert.ok((await lstat(source)).isDirectory(), `Expected package directory: ${source}`);
      const entries = await collectFiles(source, `${packageName}/${tree}`);
      const names = new Set(entries.map((file) => file.path));
      const required = tree === 'dist' ? ['index.js', 'index.d.ts'] : ['index.ts'];
      for (const name of required) assert.ok(names.has(`${packageName}/${tree}/${name}`),
        `Missing package entry: ${packageName}/${tree}/${name}`);
      files.push(...entries);
    }
  }
  const previous = await inspectPath(canonicalRoot, outputParts);
  if (previous) {
    assert.ok((await lstat(previous)).isDirectory(), 'Generated output must be a directory');
    await collectFiles(previous); // Refuse links even inside previous generated output.
  }

  // This is the single fixed, owned generated directory. Recheck canonical
  // ancestors immediately before removing stale files; never delete a source.
  assert.equal(await realpath(canonicalRoot), canonicalRoot);
  await inspectPath(canonicalRoot, outputParts);
  assertInside(canonicalRoot, directory);
  await rm(directory, { recursive: true, force: true });
  await mkdir(directory, { recursive: true });
  for (const file of files) {
    const destination = join(directory, ...file.path.split('/'));
    assertInside(directory, destination);
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, file.content);
  }

  const actual = await collectFiles(directory);
  const expected = new Map(files.map((file) => [file.path, file.content]));
  assert.equal(actual.length, expected.size, 'Generated package file list changed');
  for (const file of actual) {
    assert.ok(expected.has(file.path), `Unexpected generated file: ${file.path}`);
    assert.ok(file.content.equals(expected.get(file.path)), `Generated bytes differ: ${file.path}`);
  }
  return {
    directory,
    files: actual.map(({ path, content }) => ({ path, bytes: content.length, sha256: digest(content) })),
  };
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await prepareEdgePackages();
  process.stdout.write(`Prepared ${packageNames.length} Edge packages (${result.files.length} byte-identical files).\n`);
}
